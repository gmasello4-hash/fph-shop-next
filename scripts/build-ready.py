import re,os,glob,json,subprocess
from PIL import Image
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXCLUDE={"moody-kitchen-edit","cozy-gift-basket","dark-organic-bath"}  # not approved for promotion
src=open(f"{ROOT}/data/boards.ts").read()
slugs=re.findall(r'"slug": "([^"]+)"',src); titles=dict(re.findall(r'"slug": "([^"]+)",\s*"title": "([^"]+)"',src))
def added(s):
  out=subprocess.run(["git","log","--reverse","--format=%ct","-S",f'"slug": "{s}"',"--","data/boards.ts"],cwd=ROOT,capture_output=True,text=True).stdout.split()
  return int(out[0]) if out else 0
caps={}
for f in glob.glob("/workspace/gina-plans/pins/FPH-Boards/**/*.md",recursive=True):
  b=os.path.basename(f); m=re.match(r'^(?:\d+-)?fph-(.+?)(?:-(?:realistic-|classic-)?v\d+|-giftguide-test)?-links\.md$',b)
  t=open(f).read(); c=re.search(r'^##\s*Caption\s*\n(.*?)(?=^##\s|\Z)',t,re.S|re.M)
  if m and c: caps[m.group(1)]=c.group(1).strip()
bob=open("/workspace/gina-plans/pins/FPH-Boards/captions-for-bob.md").read()
bob_slug={};bob_title={}
for m in re.finditer(r'^##\s+(.+?)\s*\n(.*?)(?=^##\s|\Z)',bob,re.S|re.M):
  t,body=m.group(1).strip(),m.group(2); sm=re.search(r'^slug:\s*(\S+)',body,re.M)
  txt=re.sub(r'^slug:.*\n','',body,flags=re.M).strip()
  if not txt: continue
  if sm: bob_slug[sm.group(1)]=txt
  bob_title[t.lower()]=txt
def caption_for(s):
  return caps.get(s) or bob_slug.get(s) or bob_title.get(titles.get(s,"").lower())
def fix(c):
  n=[0]
  def keep(m):
    if m.group(0).lower()=="#ad": return m.group(0)
    n[0]+=1; return m.group(0) if n[0]<=4 else ""
  if not re.search(r'#ad\b',c,re.I): c="#ad "+c
  c=re.sub(r'#\w+',keep,c); return re.sub(r'[ \t]+',' ',c).replace(' \n','\n').strip()
def pad(img,W,H,out):
  im=Image.open(img).convert("RGB"); w,h=im.size; s=min(W/w,H/h); im2=im.resize((round(w*s),round(h*s)),Image.LANCZOS)
  px=lambda box: Image.open(img).convert("RGB").crop(box).resize((1,1),Image.BOX).getpixel((0,0))
  can=Image.new("RGB",(W,H)); x=(W-im2.width)//2; y=(H-im2.height)//2
  if x>0:
    can.paste(Image.new("RGB",(x+1,H),px((0,0,3,h))),(0,0)); can.paste(Image.new("RGB",(W-x-im2.width+1,H),px((w-3,0,w,h))),(x+im2.width-1,0))
  if y>0:
    can.paste(Image.new("RGB",(W,y+1),px((0,0,w,3))),(0,0)); can.paste(Image.new("RGB",(W,H-y-im2.height+1),px((0,h-3,w,h))),(0,y+im2.height-1))
  can.paste(im2,(x,y)); can.save(out,quality=90)
rows=[];gen=reuse=0
for i,s in enumerate(slugs):
  if s in EXCLUDE: continue
  b=f"{ROOT}/public/boards/{s}.png"; pad(b,1080,1350,f"{ROOT}/public/ready/{s}-feed.jpg")
  if os.path.exists(f"{ROOT}/public/stories/{s}.png"): story=f"/stories/{s}.png"; reuse+=1
  else: pad(b,1080,1920,f"{ROOT}/public/ready/{s}-story.jpg"); story=f"/ready/{s}-story.jpg"; gen+=1
  rows.append(dict(slug=s,title=titles.get(s,s),feed=f"/ready/{s}-feed.jpg",story=story,caption=fix(caption_for(s)) if caption_for(s) else None,_k=(added(s),-i)))
rows.sort(key=lambda r:r["_k"],reverse=True)
for r in rows: r.pop("_k")
open(f"{ROOT}/data/ready.ts","w").write("// Generated by scripts/build-ready.py. Captions come only from Board Builder links.md '## Caption'.\nexport type ReadyCard={slug:string;title:string;feed:string;story:string;caption:string|null};\nexport const ready:ReadyCard[]="+json.dumps(rows,indent=1,ensure_ascii=False)+";\n")
print(len(rows),"cards; stories generated",gen,"reused",reuse,"; no caption:",[r["slug"] for r in rows if not r["caption"]])
